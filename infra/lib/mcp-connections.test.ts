import { describe, it, expect } from "vitest";
import { fnNamed, statementsOf, template } from "./test-templates.js";

const ROUTES = [
  "POST /rooms/{roomId}/connections/mcp", "POST /rooms/{roomId}/connections/mcp/{name}/reconnect",
  "POST /rooms/{roomId}/connections/mcp/{name}/refresh", "DELETE /rooms/{roomId}/connections/mcp/{name}", "POST /mcp-flows/finish",
];

const tokenKey = (stage: "local" | "aws" = "local") =>
  Object.entries(template(stage).findResources("AWS::SecretsManager::Secret", { Properties: { Name: `cl-${stage}-token-key` } }));

describe("room MCP connections", () => {
  it("one Lambda serves the five MCP routes, behind the JWT authorizer", () => {
    const { logicalId } = fnNamed("cl-local-mcp-connections");
    const integrations = template().findResources("AWS::ApiGatewayV2::Integration");
    const routes = Object.values(template().findResources("AWS::ApiGatewayV2::Route")).map((r: any) => r.Properties);
    for (const key of ROUTES) {
      const route = routes.find((p) => p.RouteKey === key);
      expect(route, key).toBeDefined();
      expect(route.AuthorizationType, key).toBe("JWT");
      const integration = String(route.Target["Fn::Join"][1][1].Ref);
      expect(JSON.stringify(integrations[integration]), key).toContain(logicalId);
    }
  });

  it("the token key is generated by CloudFormation, so no one ever types it; it outlives a stack on AWS only", () => {
    const [[, local]] = tokenKey() as [string, any][];
    expect(local.Properties.GenerateSecretString).toEqual({ PasswordLength: 64, ExcludePunctuation: true });
    expect(local.DeletionPolicy).toBe("Delete");
    const [[, aws]] = tokenKey("aws") as [string, any][];
    expect(aws).toMatchObject({ DeletionPolicy: "Retain", UpdateReplacePolicy: "Retain" });
  });

  it("has 30 s, the table, the token key's name and the site's origins, and may tell the room", () => {
    const { props } = fnNamed("cl-local-mcp-connections");
    expect(props.Timeout).toBe(30);
    expect(props.Environment.Variables).toMatchObject({
      TOKEN_KEY_SECRET: "cl-local-token-key", SITE_ORIGINS: "http://localhost:3000,http://localhost:3100", TABLE_NAME: { Ref: expect.any(String) },
    });
    expect(JSON.stringify(props.Environment.Variables.MCP_BASE_URL)).toMatch(/"http:\/\/".*"\.execute-api\.localhost\.floci\.io:4566"/);
    expect(props.Environment.Variables.WS_CALLBACK_URL).toBeDefined();
    expect(fnNamed("cl-aws-mcp-connections", "aws").props.Environment.Variables).toMatchObject({ SITE_ORIGINS: "https://chat.amanarya.com", MCP_BASE_URL: "https://chat.amanarya.com" });
  });

  it("reaches this machine's test server only on the local stage", () => {
    // Allowing http and private addresses for these hosts on AWS would open the Lambdas to SSRF into AWS's network.
    for (const name of ["mcp-connections", "run"]) {
      expect(fnNamed(`cl-local-${name}`).props.Environment.Variables.MCP_LOCAL_HOSTS, name).toBe("host.docker.internal,localhost,127.0.0.1");
      expect(fnNamed(`cl-aws-${name}`, "aws").props.Environment.Variables, name).not.toHaveProperty("MCP_LOCAL_HOSTS");
    }
  });

  it("the run and MCP connections functions may read the token key, and no other function", () => {
    const [[keyId]] = tokenKey();
    const readers = Object.values(template().findResources("AWS::Lambda::Function"))
      .map((fn: any) => ({ name: fn.Properties.FunctionName as string, props: fn.Properties }))
      .filter((fn) => statementsOf(fn).some((s: any) => [s.Action].flat().includes("secretsmanager:GetSecretValue") && s.Resource.Ref === keyId))
      .map((fn) => fn.name);
    expect(readers.sort()).toEqual(["cl-local-mcp-connections", "cl-local-run"]);
    expect(fnNamed("cl-local-run").props.Environment.Variables).toMatchObject({ TOKEN_KEY_SECRET: "cl-local-token-key" });
  });
});
